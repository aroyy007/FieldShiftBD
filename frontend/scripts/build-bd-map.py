"""Build src/data/bd-districts.generated.ts from geoBoundaries BGD ADM2 (simplified).

Source: geoBoundaries gbOpen BGD ADM2 (Bangladesh Bureau of Statistics, OCHA ROAP 2020),
CC BY 3.0 IGO. https://www.geoboundaries.org  —  download the
`geoBoundaries-BGD-ADM2_simplified.geojson` release file and pass its path:

    python3 scripts/build-bd-map.py path/to/geoBoundaries-BGD-ADM2_simplified.geojson

The output is an equirectangular SVG projection (cos 24° longitude scaling) with
Douglas-Peucker simplification; it is for orientation only, not survey use.
"""
import json
import math
import sys
from pathlib import Path

LON0, LAT1 = 88.0, 26.7          # projection origin (west, north)
SCALE = 1000 / 4.7                # viewBox units per degree of latitude
KX = SCALE * math.cos(math.radians(24))
TOLERANCE = 0.006                # degrees
OFFICIAL = {  # geoBoundaries name -> current official English spelling
    'Barisal': 'Barishal', 'Bogra': 'Bogura', 'Brahamanbaria': 'Brahmanbaria', 'Chittagong': 'Chattogram',
    'Comilla': 'Cumilla', 'Jessore': 'Jashore', 'Nawabganj': 'Chapai Nawabganj', 'Maulvibazar': 'Moulvibazar',
    'Netrakona': 'Netrokona', 'Jhalokati': 'Jhalakathi', 'Khagrachhari': 'Khagrachari',
}


def project(lon, lat):
    return (lon - LON0) * KX, (LAT1 - lat) * SCALE


def dp(points, tol):
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy) or 1e-12
    index, dmax = 0, 0.0
    for i, (x, y) in enumerate(points[1:-1], 1):
        d = abs(dy * x - dx * y + x2 * y1 - y2 * x1) / norm
        if d > dmax:
            index, dmax = i, d
    if dmax <= tol:
        return [points[0], points[-1]]
    return dp(points[:index + 1], tol)[:-1] + dp(points[index:], tol)


def dp_ring(ring, tol):
    # A closed ring has identical endpoints; split at the farthest vertex first.
    start = ring[0]
    far = max(range(len(ring)), key=lambda i: math.hypot(ring[i][0] - start[0], ring[i][1] - start[1]))
    return dp(ring[:far + 1], tol)[:-1] + dp(ring[far:], tol)


def ring_area(ring):
    return abs(sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]))) / 2


def main(src: str) -> None:
    data = json.loads(Path(src).read_text())
    out, xs, ys = [], [], []
    for feature in data['features']:
        name = feature['properties']['shapeName']
        geom = feature['geometry']
        polygons = geom['coordinates'] if geom['type'] == 'MultiPolygon' else [geom['coordinates']]
        parts, cx, cy, total = [], 0.0, 0.0, 0.0
        largest = max(ring_area(polygon[0]) for polygon in polygons)
        for polygon in polygons:
            outer = polygon[0]
            area = ring_area(outer)
            if area < 0.0008 and area < largest:     # drop tiny islands and slivers
                continue
            simple = dp_ring([tuple(p) for p in outer], TOLERANCE)
            if len(simple) < 4:
                simple = [tuple(p) for p in outer]
            pts = [project(lon, lat) for lon, lat in simple]
            xs += [p[0] for p in pts]; ys += [p[1] for p in pts]
            parts.append('M' + 'L'.join(f'{x:.0f},{y:.0f}' for x, y in pts) + 'Z')
            mx, my = project(sum(p[0] for p in outer) / len(outer), sum(p[1] for p in outer) / len(outer))
            cx, cy, total = cx + mx * area, cy + my * area, total + area
        out.append({'name': OFFICIAL.get(name, name), 'd': ''.join(parts),
                    'center': [round(cx / total, 1), round(cy / total, 1)]})
    out.sort(key=lambda item: item['name'])
    width, height = math.ceil(max(xs)), math.ceil(max(ys))
    body = ',\n'.join(f"  {{ name: {json.dumps(o['name'])}, center: [{o['center'][0]}, {o['center'][1]}], d: {json.dumps(o['d'])} }}" for o in out)
    ts = f"""/* Generated by scripts/build-bd-map.py. Do not edit.
 * District boundaries: geoBoundaries BGD ADM2 (BBS, OCHA ROAP 2020), CC BY 3.0 IGO.
 * Simplified for orientation only; not for survey or legal boundary use. */
export const BD_MAP = {{ lon0: {LON0}, lat1: {LAT1}, kx: {KX:.6f}, scale: {SCALE:.6f}, width: {width}, height: {height} }} as const;
export const BD_MAP_CREDIT = 'District boundaries: geoBoundaries (BBS, OCHA) · CC BY 3.0 IGO';
export type DistrictShape = {{ name: string; center: [number, number]; d: string }};
export const BD_DISTRICTS: DistrictShape[] = [
{body}
];
"""
    target = Path(__file__).resolve().parents[1] / 'src/data/bd-districts.generated.ts'
    target.write_text(ts, encoding='utf-8')
    print(f'{target.name}: {len(out)} districts, {len(ts) / 1024:.0f} KB, viewBox {width}x{height}')


if __name__ == '__main__':
    main(sys.argv[1])
