"""Print v2 TypeScript contracts without modifying the existing v1 exporter."""
import json
from app.contracts.challenge.v2 import RotationCompareRequest, RotationComparisonV2
from scripts.export_challenge_contracts import _type_for


def typescript():
    definitions = {}
    for model in (RotationCompareRequest, RotationComparisonV2):
        schema = model.model_json_schema(ref_template='#/$defs/{model}')
        definitions.update(schema.pop('$defs', {}))
        definitions[model.__name__] = schema
    lines = ['/* Generated by backend/scripts/export_rotation_contracts.py. Do not edit. */',
             'export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };']
    lines += [f'export type {name} = {_type_for(schema)};' for name, schema in sorted(definitions.items())]
    return '\n'.join(lines)+'\n'


if __name__ == '__main__':
    print(typescript(), end='')
